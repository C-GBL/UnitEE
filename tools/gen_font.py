# Lowercase reuses the uppercase shapes. A debug overlay does not need a second
# typeface, and every byte here is a byte of a 32 MB budget.
for c in "abcdefghijklmnopqrstuvwxyz":
    G[c] = G[c.upper()]

FIRST, LAST = 32, 126
missing = [chr(c) for c in range(FIRST, LAST + 1) if chr(c) not in G]
assert not missing, "missing glyphs: %r" % missing

lines = [
    "// Generated by tools/gen_font.py -- do not edit by hand.",
    "//",
    "// 8x8 fixed-width bitmap font for printable ASCII 32..126, one byte per row,",
    "// MSB leftmost. Lowercase deliberately reuses the uppercase shapes: a debug",
    "// overlay does not need a second typeface.",
    "#pragma once",
    "",
    "#include <cstdint>",
    "",
    "namespace ps2ur {",
    "namespace gfx {",
    "",
    "inline constexpr uint32_t kFontFirstChar = %d;" % FIRST,
    "inline constexpr uint32_t kFontLastChar = %d;" % LAST,
    "inline constexpr uint32_t kFontGlyphWidth = 8;",
    "inline constexpr uint32_t kFontGlyphHeight = 8;",
    "",
    "inline constexpr uint8_t kFontGlyphs[][8] = {",
]
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    rows = ", ".join("0x%02X" % b for b in G[ch])
    if ch == ' ':
        label = "space"
    elif ch == '\\':
        label = "backslash"
    else:
        label = ch
    lines.append("    {%s}, // %d '%s'" % (rows, code, label))
lines.append("};")
lines.append("")
lines.append("} // namespace gfx")
lines.append("} // namespace ps2ur")

dest = os.path.join("runtime", "include", "ps2ur", "gs_font.h")
with open(dest, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
print("wrote %s with %d glyphs" % (dest, LAST - FIRST + 1))
